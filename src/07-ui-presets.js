function avatarView(a, size){
  size = size || 'md';
  if (a && a.avatar && a.avatar.custom) return '<span class="avatar '+size+'"><img src="'+esc(a.avatar.custom)+'" alt=""></span>';
  var emoji = (a && a.avatar && a.avatar.preset) || (a && a.kind==='npc' ? '🧟' : AVATAR_DEFAULT_PC);
  return '<span class="avatar '+size+'">'+esc(emoji)+'</span>';
}
function defaultAvatarForActor(kind, side){
  if (kind==='npc'){ if (side==='盟友') return '🦸'; if (side==='中立') return '🧔'; return '🧟'; }
  return AVATAR_DEFAULT_PC;
}
function attrTileHTML(k, val, editable){
  var lb = ATTR_LABELS.filter(function(x){return x[0]===k;})[0];
  var en = lb?lb[1]:k, cn = lb?lb[2]:'';
  if (editable) return '<div class="cell"><div class="en">'+en+'</div><input type="number" class="am-attr" data-k="'+k+'" value="'+(val||0)+'" min="0" title="'+cn+'"></div>';
  return '<div class="cell"><div class="en">'+en+'</div><div class="val" title="'+cn+'">'+(val||0)+'</div></div>';
}
function attrs3x3(a, editable){
  var order=['str','dex','pow','con','app','edu','siz','int','luck'];
  return '<div class="attrgrid">'+order.map(function(k){ return attrTileHTML(k, a.attrs[k], editable); }).join('')+'</div>';
}
function barsHTML(a){
  function barRow(label, cur, max, cls){
    var c = Math.max(0,cur||0), m = Math.max(1,max||1);
    var pct = Math.max(0,Math.min(100,Math.round(c/m*100)));
    return '<div class="brow"><span>'+label+'</span><div class="bar '+cls+'"><i style="width:'+pct+'%"></i></div><span>'+c+'/'+m+'</span></div>';
  }
  return '<div class="bars3">'+
    barRow('HP',a.hp.cur,a.hp.max,'hp')+
    barRow('SAN',a.san? a.san.cur:0,a.san?a.san.max:99,'purple')+
    barRow('MP',a.mp?a.mp.cur:0,a.mp?a.mp.max:0,'blue')+'</div>';
}
function actorTag(a){
  var s=sideOf(a);
  return '<span class="sidebadge side-'+esc(s)+'">'+esc(s)+'</span>';
}
