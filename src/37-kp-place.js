/* 由地图上的地点名认种类。
   「命中的关键词最长」优先（同样长时前面定义的优先），所以「弹药库」归军械库、不会被「药库」抢走，
   「湖畔小屋」归湖畔、不会被笼统的「小屋」抢走。认不出就返回 null（调用方会用地图 / 场景语境兜底）。 */
function kpKindByWord(name){
  var s=String(name||''), best=null, bl=0, i, j;
  for(i=0;i<KP_PLACE_KINDS.length;i++){
    var e=KP_PLACE_KINDS[i];
    for(j=0;j<e.w.length;j++){
      var w=e.w[j];
      if(w.length>bl && s.indexOf(w)>=0){ bl=w.length; best=e; }
    }
  }
  return best;
}
function kpKindOf(k){
  for(var i=0;i<KP_PLACE_KINDS.length;i++) if(KP_PLACE_KINDS[i].k===k) return KP_PLACE_KINDS[i];
  return null;
}

